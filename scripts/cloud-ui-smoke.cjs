const {app,BrowserWindow}=require('electron');
const path=require('node:path');
const fs=require('node:fs');
const assert=require('node:assert/strict');
const {startServer}=require('../dist/server.cjs');
let backend,win;
const evaluate=expression=>win.webContents.executeJavaScript(expression);
const waitFor=async expression=>{for(let i=0;i<150;i++){if(await evaluate(`Boolean(${expression})`))return;await new Promise(r=>setTimeout(r,100));}throw new Error('UI condition timed out: '+expression);};
app.whenReady().then(async()=>{
  backend=await startServer({rootDir:path.resolve(__dirname,'..'),cloudGenerationOnly:true});
  win=new BrowserWindow({show:false,width:1440,height:900,webPreferences:{preload:path.join(__dirname,'cloud-ui-preload.cjs'),contextIsolation:false,nodeIntegration:false,sandbox:false}});
  const errors=[]; win.webContents.on('console-message',(_e,level,message)=>{if(level===3)errors.push(message);});
  await win.loadURL(backend.url);
  await waitFor(`document.body.innerText.includes('余额不足，请先充值')`);
  assert.equal(await evaluate(`document.querySelector('.btn-start').disabled`),true,'empty balance button');
  await evaluate(`document.querySelector('.btn-start').click()`);
  assert.equal(await evaluate('window.__cloudTest.posts.length'),0);
  await evaluate('window.__cloudTest.balance=100');
  await waitFor(`!document.querySelector('.btn-start').disabled`);
  fs.writeFileSync(path.join(__dirname,'../outputs/workbench-idle.png'),(await win.webContents.capturePage()).toPNG());
  await evaluate(`document.querySelector('.btn-start').click()`);
  await waitFor('window.__cloudTest.posts.length===1');
  const sent=await evaluate('window.__cloudTest.posts[0]');
  assert.deepEqual(Object.keys(sent).sort(),['duration','features','product','region','requestId','targetAudience']);
  await waitFor(`document.querySelector('.btn-start').disabled`);
  await evaluate(`window.__cloudTest.job={...window.__cloudTest.job,status:'succeeded',scripts:[1,2,3].map(i=>({title:'验收脚本'+i,style:'演示',hook:'开场',script:[{timestamp:'0-3s',visual:'展示产品',audio:'hello'}],cta:'查看产品'}))}`);
  await waitFor(`document.body.innerText.includes('验收脚本3')`);
  assert.equal(await evaluate(`document.querySelector('.btn-start').disabled`),true,'post-generation balance button');
  assert.equal(await evaluate(`window.__cloudTest.balance`),40);
  fs.writeFileSync(path.join(__dirname,'../outputs/workbench-success.png'),(await win.webContents.capturePage()).toPNG());
  await evaluate(`window.__cloudTest.update({state:'available',version:'1.0.18',releaseNotes:'真实更新日志验收'});`);
  await waitFor(`document.body.innerText.includes('V1.0.18')`);
  await evaluate(`document.querySelector('.ota').click()`);
  await waitFor(`document.querySelector('.modal-panel')`);
  assert.equal(await evaluate(`document.body.innerText.includes('真实更新日志验收')`),true);
  await evaluate(`document.querySelector('.modal-panel .btn-dark').click()`);
  await waitFor(`window.__cloudTest.downloads===1`);
  await evaluate(`document.querySelector('.modal-header button').click()`);
  await evaluate(`Array.from(document.querySelectorAll('button')).find(b=>b.textContent==='去充值').click()`);
  await waitFor(`document.querySelector('#recharge-amount')`);
  await waitFor(`!document.querySelector('.modal-panel .btn-dark').disabled`);
  await evaluate(`document.querySelector('.modal-panel .btn-dark').click()`);
  await waitFor(`document.body.innerText.includes('test-order123456')`);
  await evaluate(`document.querySelector('.modal-panel .btn-dark').click()`);
  await waitFor(`window.__cloudTest.proofs===1`);
  assert.equal(await evaluate(`window.__cloudTest.balance`),40,'proof cannot increase balance');
  assert.equal(await evaluate(`window.__cloudTest.calls.every(x=>x.url.startsWith('https://107-173-144-109.nip.io:8443/'))`),true,JSON.stringify(await evaluate('window.__cloudTest.calls')));
  assert.equal(errors.length,0,errors.join('\n'));
  fs.writeFileSync(path.join(__dirname,'../outputs/cloud-ui-smoke.json'),JSON.stringify({ok:true,checks:['zero balance blocked without HTTP generation','balance refresh enables generation','server-only request without key or price','running task prevents duplicate submission','result and reduced balance displayed']}));
  await evaluate(`document.querySelector('.modal-header button').click()`);
  win.setSize(1060,800);
  await evaluate(`document.querySelectorAll('.collapse-head').forEach(b=>b.click())`);
  await new Promise(r=>setTimeout(r,500));
  assert.equal(await evaluate(`document.documentElement.scrollWidth <= window.innerWidth`),true,'small window must not overflow horizontally');
  fs.writeFileSync(path.join(__dirname,'../outputs/workbench-small.png'),(await win.webContents.capturePage()).toPNG());
  win.destroy(); await backend.close(); app.exit(0);
}).catch(async e=>{fs.writeFileSync(path.join(__dirname,'../outputs/cloud-ui-smoke.json'),JSON.stringify({ok:false,error:e.stack}));if(win)win.destroy();if(backend)await backend.close();app.exit(1);});
setTimeout(()=>app.exit(2),60000).unref();
